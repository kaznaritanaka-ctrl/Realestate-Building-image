/** 都道府県+市区町村名から管轄法務局を引く。郡名の有無ゆらぎにも対応する。 */
export function houmukyokuFor(pref: string, city: string): Houmukyoku | null {
  const direct = HOUMUKYOKU[pref + city];
  if (direct) return direct;
  // 「○○郡○○町」と「○○町」のゆらぎを吸収する
  const stripped = city.replace(/^[^市区町村]*郡/, "");
  if (stripped !== city) { const h = HOUMUKYOKU[pref + stripped]; if (h) return h; }
  for (const k of Object.keys(HOUMUKYOKU)) {
    if (!k.startsWith(pref)) continue;
    if (k.slice(pref.length).replace(/^[^市区町村]*郡/, "") === city) return HOUMUKYOKU[k];
  }
  return null;
}
